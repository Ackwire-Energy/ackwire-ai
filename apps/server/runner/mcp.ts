/** Quotes one argument for the platform shell the wrapper uses (`/bin/sh -c`, or `cmd /s /c`). */
export function shellArg(value: string, platform: NodeJS.Platform = process.platform) {
  if (platform === "win32") return `"${value.replace(/"/g, "")}"`;
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * The mission's rules as one safe argument: letters, digits, spaces and plain
 * punctuation only (no quoting surprises in any shell, `%`/`!` for cmd included).
 */
export function cleanRules(rules: string) {
  return rules
    .replace(/[^A-Za-z0-9 .,:;()/_\-?]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 4000);
}

/**
 * Where the task runs and its folders, for our MCP process (`AGENTES_MCP_CWD`, `AGENTES_MCP_FOLDERS`), and
 * the runner's own home (`AGENTES_RUNNER_HOME`), which is never read.
 */
export function mcpScopeFromEnv(env: NodeJS.ProcessEnv): CommandScope | undefined {
  const cwd = env.AGENTES_MCP_CWD?.trim();
  if (!cwd || !path.isAbsolute(cwd)) return undefined;
  const folders = (env.AGENTES_MCP_FOLDERS ?? "").split(path.delimiter).filter((f) => f && path.isAbsolute(f));
  const runnerHome = env.AGENTES_RUNNER_HOME?.trim();
  return {
    cwd,
    folders: folders.length ? folders : [cwd],
    ...(env.HOME ? { home: env.HOME } : {}),
    ...(runnerHome && path.isAbsolute(runnerHome) ? { runnerHome } : {}),
  };
}

/** The turn's permission profile for our MCP process (`AGENTES_MCP_PROFILE`): anything but `plan` is `work`. */
export const mcpProfileFromEnv = (env: NodeJS.ProcessEnv): CommandProfile =>
  env.AGENTES_MCP_PROFILE === "plan" ? "plan" : "work";

/** The MCP config Claude Code reads (`--mcp-config <file>`): our server, bound to the task. */
export function claudeMcpConfig(input: {
  command: string[];
  taskId: string;
  socketPath: string;
  token: string;
  /** Where the task runs and the mission folder (plain reads there need no card). */
  cwd?: string;
  folders?: string[];
  /** Claude Code lists our tools up front instead of behind its ToolSearch. */
  alwaysLoad?: boolean;
  /** A `plan` turn: its permission prompts are answered by the computer alone (reads only). */
  profile?: CommandProfile;
  /** The runner's home: the MCP process finds the runner there and never lets it be read. */
  runnerHome?: string;
}) {
  const [command, ...args] = input.command;
  return {
    mcpServers: {
      agentes: {
        type: "stdio",
        command,
        args: [...args, "mcp", "--task", input.taskId],
        ...(input.alwaysLoad ? { alwaysLoad: true } : {}),
        env: {
          AGENTES_MCP_TOKEN: input.token,
          AGENTES_MCP_SOCKET: input.socketPath,
          ...(input.cwd ? { AGENTES_MCP_CWD: input.cwd } : {}),
          ...(input.folders?.length ? { AGENTES_MCP_FOLDERS: input.folders.join(path.delimiter) } : {}),
          ...(input.profile === "plan" ? { AGENTES_MCP_PROFILE: "plan" } : {}),
          ...(input.runnerHome ? { AGENTES_RUNNER_HOME: input.runnerHome } : {}),
        },
      },
    },
  };
}

/** Mission branches: `agentes/<last 8 hex of the mission id>/` unless the server sends its own prefix. */
export function missionBranchPrefix(missionId: string, given?: string) {
  const clean = (given ?? "").replace(/[^A-Za-z0-9/_.-]/g, "").replace(/^\/+/, "");
  if (clean.endsWith("/") && !clean.includes("..") && clean.length <= 80) return clean;
  return `agentes/${missionId.replace(/[^a-zA-Z0-9]/g, "").slice(-8)}/`;
}

