/**
 * The local `agentes` MCP server of a mission task (protocol 5, ADR 0029).
 *
 * - `agentes-runner mcp --task <taskId>` is a stdio MCP server the executor
 *   (Claude Code, Codex) starts from its MCP config. It speaks the minimal
 *   MCP JSON-RPC (`initialize`, `tools/list`, `tools/call`, `ping`), one JSON
 *   message per line, and forwards each tool call to the runner daemon.
 * - The daemon (`agentes-runner start`) listens on a local endpoint in the
 *   runner home (a unix socket; a named pipe on Windows). Each request carries
 *   the task id and the task's random token, generated by the daemon when it
 *   started the task (in the executor's MCP config env, and in the task's
 *   folder, mode 600). Only a running mission task with the right token gets
 *   through; the daemon relays it to the server as `mcp.call` and the
 *   server's `mcp.result` comes back the same way.
 * - The server decides everything (the task must be this machine's and the
 *   mission's); the runner only checks the token.
 */

/** Daemon side: what a task needs to call through the bridge. */
export interface McpTaskInfo {
  token: string;
  missionId: string;
  running: boolean;
  /** Where the task runs (absolute) and its agent's folder (absolute): paths the executor gives are resolved here. */
  cwd?: string;
  folder?: string;
  /** The agent's secrets masked (ADR 0027): nothing the executor sends leaves the machine with them. */
  redact?: (text: string) => string;
}

/** Every string inside `value` through `redact` (keys kept). */
export function redactDeep(value: unknown, redact: (text: string) => string): unknown {
  if (typeof value === "string") return redact(value);
  if (Array.isArray(value)) return value.map((v) => redactDeep(v, redact));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, redactDeep(v, redact)]),
    );
  }
  return value;
}

/** Paths in the agent's folder but outside the task's own folder travel with this prefix (the server resolves it). */
export const FOLDER_PATH_PREFIX = "@folder/";

/**
 * A path the executor gave (`upload_artifact`, `request_review`), as the
 * server expects it: relative to the task's folder; an absolute one inside
 * the task's folder becomes relative, one elsewhere in the agent's folder
 * gets `@folder/`, anything outside is refused (null).
 */
export function resolveTaskPath(given: string, info: Pick<McpTaskInfo, "cwd" | "folder">): string | null {
  const p = given.trim();
  if (!p) return p;
  const absolute = path.isAbsolute(p) || /^[a-zA-Z]:[\\/]/.test(p);
  if (!absolute) return p;
  const abs = path.resolve(p);
  const inside = (root: string | undefined) => {
    if (!root) return null;
    const rel = path.relative(root, abs);
    return rel === "" || (!rel.startsWith("..") && !path.isAbsolute(rel)) ? rel.split(path.sep).join("/") : null;
  };
  const inCwd = inside(info.cwd);
  if (inCwd !== null) return inCwd || ".";
  const inFolder = inside(info.folder);
  if (inFolder !== null) return `${FOLDER_PATH_PREFIX}${inFolder}`;
  return null;
}

const PATH_ARGS: Record<string, "path" | "paths"> = {
  upload_artifact: "path",
  request_review: "paths",
  complete_mission: "paths",
};

export interface IpcRequest {
  taskId: string;
  token: string;
  tool: string;
  args: Record<string, unknown>;
}

/** `transient`: the link to the runner or to agentes.chat was down; asking again later may work. */
export type IpcReply = { ok: true; text: string } | { ok: false; error: string; transient?: boolean };

/** Where the daemon listens: `<runner home>/mcp.sock`, or a named pipe on Windows. */
export function mcpSocketPath(home: string, platform: NodeJS.Platform = process.platform) {
  if (platform === "win32") {
    return `\\\\.\\pipe\\agentes-runner-${createHash("sha256").update(home).digest("hex").slice(0, 16)}`;
  }
  return path.join(home, "mcp.sock");
}

export const newMcpToken = () => randomBytes(24).toString("base64url");

/** The token file in a task's folder (the MCP process reads it when its env has none). */
export const MCP_TOKEN_FILE = "mcp-token";

const sameToken = (a: string, b: string) => {
  const x = Buffer.from(a);
  const y = Buffer.from(b);
  return x.length === y.length && timingSafeEqual(x, y);
};

/** Calls the bridge may send again after a reconnect (the server answers them the same way twice). */
const RESEND_SAFE = new Set<string>([PERMISSION_TOOL, "get_context"]);

/** How long a relayed call may take (an upload of a large file takes minutes). */
export const MCP_CALL_TIMEOUT_MS = 6 * 60_000;

/**
 * The daemon's half: a local endpoint for the MCP processes of this
 * machine's mission tasks, relaying their calls to the server.
 */
export class McpBridge {
  private server: Server | null = null;
  private send: ((frame: RunnerFrame) => void) | null = null;
  private readonly pending = new Map<
    string,
    { resolve: (r: IpcReply) => void; timer: ReturnType<typeof setTimeout>; frame: RunnerFrame; tool: string }
  >();
  /** Calls made while the connection is down (a restart, a reconnect): relayed once it is back. */
  private readonly waiting = new Map<string, { frame: RunnerFrame; tool: string }>();

  constructor(
    private readonly opts: {
      socketPath: string;
      /** The task's MCP token and state (from the task journal). */
      task: (taskId: string) => McpTaskInfo | null;
      log?: (line: string) => void;
      callTimeoutMs?: number;
    },
  ) {}

  get socketPath() {
    return this.opts.socketPath;
  }

  /** Starts listening (a stale socket file from a previous runner is removed first). */
  async listen() {
    if (this.server) return;
    if (process.platform !== "win32" && existsSync(this.opts.socketPath)) rmSync(this.opts.socketPath, { force: true });
    const server = createServer((socket) => this.serve(socket));
    const events = server as unknown as EventEmitter;
    await new Promise<void>((resolve, reject) => {
      events.once("error", reject);
      server.listen(this.opts.socketPath, () => {
        events.off("error", reject);
        resolve();
      });
    });
    events.on("error", (err: Error) => this.opts.log?.(`mcp endpoint: ${err.message}`));
    this.server = server;
  }

  /** A connection to the server is up: calls go there, the ones that waited first. */
  attach(send: (frame: RunnerFrame) => void) {
    this.send = send;
    for (const [callId, w] of this.waiting) {
      this.waiting.delete(callId);
      this.relay(callId, w.frame);
    }
  }

  /**
   * The connection went away. Calls not answered yet: the ones safe to send
   * twice (the permission prompt, which the server keys by its request, and
   * reads) wait for the connection and go again; the others fail as
   * transient (the server may already have done them).
   */
  detach() {
    this.send = null;
    for (const [callId, p] of this.pending) {
      if (RESEND_SAFE.has(p.tool)) {
        this.waiting.set(callId, { frame: p.frame, tool: p.tool });
        continue;
      }
      clearTimeout(p.timer);
      p.resolve({
        ok: false,
        error: "The computer lost its connection to agentes.chat; try again in a minute.",
        transient: true,
      });
      this.pending.delete(callId);
    }
  }

  private relay(callId: string, frame: RunnerFrame) {
    const p = this.pending.get(callId);
    const send = this.send;
    if (!p) return;
    if (!send) {
      this.waiting.set(callId, { frame, tool: p.tool });
      return;
    }
    try {
      send(frame);
    } catch {
      // The socket broke while sending: wait for the next connection.
      this.waiting.set(callId, { frame, tool: p.tool });
    }
  }

  /** The server's answer to a call. */
  result(frame: Extract<ServerFrame, { type: "mcp.result" }>) {
    const p = this.pending.get(frame.callId);
    if (!p) return;
    clearTimeout(p.timer);
    this.pending.delete(frame.callId);
    p.resolve(frame.ok ? { ok: true, text: String(frame.text ?? "") } : { ok: false, error: frame.error.message });
  }

  /** One call from an MCP process: token checked, relayed, answered. */
  async handle(req: IpcRequest): Promise<IpcReply> {
    const taskId = typeof req.taskId === "string" ? req.taskId : "";
    const info = taskId ? this.opts.task(taskId) : null;
    if (!info || typeof req.token !== "string" || !sameToken(info.token, req.token)) {
      return { ok: false, error: "Not allowed: this task has no agentes tools." };
    }
    if (!info.running) return { ok: false, error: "This task has ended." };
    const tool = typeof req.tool === "string" ? req.tool.slice(0, 64) : "";
    if (!MISSION_MCP_TOOLS.some((t) => t.name === tool)) return { ok: false, error: `Unknown tool ${tool}` };
    const given = req.args && typeof req.args === "object" && !Array.isArray(req.args) ? req.args : {};
    if (JSON.stringify(given).length > MCP_ARGS_MAX_CHARS) return { ok: false, error: "The arguments are too large." };
    // Secrets never leave the machine through our tools (the server masks again).
    const args = (info.redact ? redactDeep(given, info.redact) : given) as Record<string, unknown>;
    const pathArg = PATH_ARGS[tool];
    if (pathArg === "path" && typeof args.path === "string") {
      const resolved = resolveTaskPath(args.path, info);
      if (resolved === null)
        return { ok: false, error: `${args.path} is outside your folder: copy it into your folder first.` };
      args.path = resolved;
    } else if (pathArg === "paths" && Array.isArray(args.paths)) {
      const out: string[] = [];
      for (const p of args.paths) {
        const resolved = typeof p === "string" ? resolveTaskPath(p, info) : null;
        if (resolved === null)
          return { ok: false, error: `${String(p)} is outside your folder: copy it into your folder first.` };
        out.push(resolved);
      }
      args.paths = out;
    }
    // Not connected right now (the runner restarting, a reconnect): the call waits for the
    // connection, bounded by its own timeout, instead of being refused.
    const callId = randomBytes(12).toString("hex");
    const frame: RunnerFrame = { type: "mcp.call", callId, taskId, tool, args };
    return new Promise<IpcReply>((resolve) => {
      const timer = setTimeout(() => {
        const waited = this.waiting.has(callId);
        this.pending.delete(callId);
        this.waiting.delete(callId);
        resolve(
          waited
            ? {
                ok: false,
                error: "The computer is not connected to agentes.chat right now; try again in a minute.",
                transient: true,
              }
            : { ok: false, error: "agentes.chat did not answer in time." },
        );
      }, this.opts.callTimeoutMs ?? MCP_CALL_TIMEOUT_MS);
      timer.unref?.();
      this.pending.set(callId, { resolve, timer, frame, tool });
      this.relay(callId, frame);
    });
  }

  private serve(socket: Socket) {
    let buf = "";
    socket.setEncoding("utf8");
    socket.on("error", () => {});
    socket.on("data", (chunk: string) => {
      buf += chunk;
      if (buf.length > MCP_ARGS_MAX_CHARS * 2) {
        socket.end(`${JSON.stringify({ ok: false, error: "Request too large" })}\n`);
        return;
      }
      const nl = buf.indexOf("\n");
      if (nl < 0) return;
      const line = buf.slice(0, nl);
      buf = "";
      let req: IpcRequest;
      try {
        req = JSON.parse(line) as IpcRequest;
      } catch {
        socket.end(`${JSON.stringify({ ok: false, error: "Bad request" })}\n`);
        return;
      }
      void this.handle(req).then((reply) => {
        if (reply.ok === false) this.opts.log?.(`mcp ${String(req.tool)} refused: ${reply.error}`);
        socket.end(`${JSON.stringify(reply)}\n`);
      });
    });
  }

  async close() {
    this.detach();
    for (const [callId, p] of this.pending) {
      clearTimeout(p.timer);
      p.resolve({ ok: false, error: "The runner is stopping; try again in a minute.", transient: true });
      this.pending.delete(callId);
    }
    this.waiting.clear();
    const server = this.server;
    this.server = null;
    if (server) await new Promise<void>((resolve) => server.close(() => resolve()));
    if (process.platform !== "win32") rmSync(this.opts.socketPath, { force: true });
  }
}

/** The MCP process's half: one request over the local endpoint. */
export function ipcCall(socketPath: string, req: IpcRequest, timeoutMs = MCP_CALL_TIMEOUT_MS + 30_000) {
  return new Promise<IpcReply>((resolve) => {
    let buf = "";
    let done = false;
    const finish = (r: IpcReply) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      socket.destroy();
      resolve(r);
    };
    const socket = createConnection(socketPath);
    const timer = setTimeout(() => finish({ ok: false, error: "The runner did not answer in time." }), timeoutMs);
    socket.setEncoding("utf8");
    socket.on("connect", () => socket.write(`${JSON.stringify(req)}\n`));
    socket.on("data", (chunk: string) => {
      buf += chunk;
      const nl = buf.indexOf("\n");
      if (nl < 0) return;
      try {
        finish(JSON.parse(buf.slice(0, nl)) as IpcReply);
      } catch {
        finish({ ok: false, error: "The runner answered something unexpected." });
      }
    });
    socket.on("error", () =>
      finish({
        ok: false,
        error: "The agentes runner is not running on this computer (start it: agentes-runner start).",
        transient: true,
      }),
    );
    socket.on("close", () => finish({ ok: false, error: "The runner closed the connection.", transient: true }));
  });
}

