/** The same git rule with `-C <path>` before the subcommand (`git -C /path status`). */
const gitC = (rules: string[]) =>
  rules.flatMap((r) => (r.startsWith("Bash(git ") ? [r, r.replace("Bash(git ", "Bash(git -C * ")] : [r]));

/** The deny list (`MISSION_DENY_RULES` in @agenteschat/adapters/command-policy, shared with the server). */
export const DENY_RULES = MISSION_DENY_RULES;

/**
 * The `--settings` file of a mission task's Claude Code (protocol 7): what
 * it may run without asking (`-p` can't ask: anything else is denied).
 * `plan`: read only: our tools, reading files and read-only shell commands
 * (`ls`, `cat`, `head`, `git status`, also `git -C <path> …`; Claude Code
 * checks each part of a pipeline). `work`: edits (`acceptEdits`), the same
 * read-only commands, plain file work, git on its own branches, pushes only
 * to branches under the mission's prefix, pull requests, tests and builds;
 * merges, other pushes and deploys are denied (they go through
 * `request_approval`). Deny rules win over allow rules.
 */
/**
 * File rules for the mission folder (absolute; `//` is Claude Code's prefix
 * for an absolute path): an item in its own worktree or subfolder reads and
 * writes the mission's `.agentes/` and its shared inputs there, and nothing
 * outside it (other paths still ask through the prompt tool).
 */
export function missionFolderRules(missionFolder: string | undefined, tools: readonly string[]) {
  const dir = (missionFolder ?? "").replace(/\\/g, "/").replace(/\/+$/, "");
  if (!dir.startsWith("/") || dir.includes("*") || /\.\.(\/|$)/.test(dir)) return [];
  return tools.map((tool) => `${tool}(/${dir}/**)`);
}

export function claudePermissionSettings(
  mode: "plan" | "work",
  branchPrefix: string,
  missionAllow: string[] = [],
  /** An item's mission folder when it runs elsewhere (its worktree or subfolder). */
  missionFolder?: string,
) {
  if (mode === "plan") {
    return {
      permissions: {
        allow: [
          "mcp__agentes",
          "Read",
          "Glob",
          "Grep",
          "LS",
          ...readOnlyShell(),
          ...gitC(GIT_READ.flatMap((c) => [`Bash(git ${c})`, `Bash(git ${c} *)`])),
          ...missionFolderRules(missionFolder, ["Read"]),
        ],
        deny: ["Edit", "Write", "NotebookEdit", ...MISSION_DENY_RULES],
      },
    };
  }
  const prefix = branchPrefix;
  return {
    permissions: {
      allow: [
        "mcp__agentes",
        ...readOnlyShell(),
        ...FILE_WORK.map((c) => `Bash(${c} *)`),
        ...gitC(GIT_WORK.flatMap((c) => [`Bash(git ${c})`, `Bash(git ${c} *)`])),
        `Bash(git push origin ${prefix}*)`,
        `Bash(git push -u origin ${prefix}*)`,
        `Bash(git push --set-upstream origin ${prefix}*)`,
        "Bash(gh pr create *)",
        "Bash(gh pr view *)",
        "Bash(gh pr list *)",
        "Bash(gh pr checks *)",
        "Bash(gh pr diff *)",
        "Bash(gh pr status *)",
        ...BUILD_RULES,
        // The mission folder, for an item working in its own worktree or subfolder.
        ...missionFolderRules(missionFolder, ["Read", "Edit", "Write"]),
        // What a person allowed for the whole mission ("Aprovar sempre nesta missão").
        ...missionAllow.filter(isSafeRule).slice(0, 100),
      ],
      deny: [...MISSION_DENY_RULES],
    },
  };
}

/**
 * Our MCP server's name in Codex's config: unique, so a server of the same
 * name in the person's `~/.codex/config.toml` is never merged into it.
 */
export const CODEX_MCP_SERVER = "agenteschat_agentes";

/** The env names Codex passes to our MCP process (values come from the task's env, never argv). */
export const CODEX_MCP_ENV = ["AGENTES_MCP_TOKEN", "AGENTES_MCP_SOCKET", "AGENTES_RUNNER_HOME"] as const;

/**
 * Codex's `-c key=value` overrides for our MCP server (values are TOML;
 * JSON strings and arrays are valid TOML). `default_tools_approval_mode =
 * "approve"` is essential: `codex exec` runs with approval_policy=never and
 * would deny every tool without `readOnlyHint` as "requires approval".
 */
export function codexMcpOverrides(input: { command: string[]; taskId: string }) {
  const [command, ...args] = input.command;
  const key = `mcp_servers.${CODEX_MCP_SERVER}`;
  const toml = (v: unknown) => JSON.stringify(v);
  return [
    `${key}.command=${toml(command ?? "node")}`,
    `${key}.args=${toml([...args, "mcp", "--task", input.taskId])}`,
    `${key}.env_vars=${toml(CODEX_MCP_ENV)}`,
    `${key}.default_tools_approval_mode="approve"`,
    `${key}.startup_timeout_sec=60`,
    `${key}.tool_timeout_sec=300`,
    `${key}.required=true`,
  ];
}

/**
 * Extra arguments for a mission task's executor. Claude Code: our MCP
 * config (added to the person's own MCP servers: no `--strict-mcp-config`),
 * the permission profile (`--settings`, see `claudePermissionSettings`), in
 * work turns our permission prompt tool (anything off the allow list asks a
 * person in the thread; the deny list never reaches it), our
 * tools allowed without a prompt (`-p` can't ask), and the rules appended
 * to its system prompt. Codex: our server through repeatable `-c` overrides
 * (token and socket through the env), and on the first turn the rules as
 * `developer_instructions` (a resumed thread keeps them).
 */
export function missionExecutorArgs(
  executor: "claude" | "codex",
  input: {
    configFile: string;
    command: string[];
    taskId: string;
    socketPath: string;
    rules: string;
    /** Claude Code: the generated permission settings file. */
    settingsFile?: string;
    /** Codex: a resumed thread already has the rules. */
    resumed?: boolean;
    /** Claude Code work turns: commands off the allow list ask a person through our tool. */
    promptTool?: boolean;
    /** Claude Code: folders it may use besides its own (an item's mission folder). */
    addDirs?: string[];
  },
  platform: NodeJS.Platform = process.platform,
): string[] {
  const q = (v: string) => shellArg(v, platform);
  const rules = cleanRules(input.rules);
  if (executor === "claude") {
    return [
      "--mcp-config",
      q(input.configFile),
      ...(input.settingsFile ? ["--settings", q(input.settingsFile)] : []),
      "--allowedTools",
      "mcp__agentes",
      ...(input.promptTool ? ["--permission-prompt-tool", PERMISSION_PROMPT_TOOL] : []),
      ...(input.addDirs ?? []).flatMap((d) => ["--add-dir", q(d)]),
      ...(rules ? ["--append-system-prompt", q(rules)] : []),
    ];
  }
  return [
    ...codexMcpOverrides(input).flatMap((o) => ["-c", q(o)]),
    ...(rules && !input.resumed ? ["-c", q(`developer_instructions=${JSON.stringify(rules)}`)] : []),
  ];
}
