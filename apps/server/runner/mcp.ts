export const MCP_PROTOCOL_VERSION = "2025-06-18";

/** Our tools that only read (MCP `readOnlyHint`). */
const READ_ONLY_TOOLS = new Set(["get_context"]);

type JsonRpcId = string | number | null;
export type ToolCaller = (tool: string, args: Record<string, unknown>) => Promise<IpcReply>;
/** The run's tools as the bridge knows them now (protocol 8). */
export type ToolLister = () => Promise<readonly McpToolInfo[]>;

/** How long the MCP process trusts its list before asking again (a `tools/list` within this is answered locally). */
export const TOOLS_CACHE_MS = 30_000;
/** How often the MCP process re-reads the list in the background (a change notifies the executor). */
export const TOOLS_REFRESH_MS = 60_000;

/**
 * The run's tool list in the MCP process (one process per task or run, so
 * the cache is per run). `get` answers from the cache while fresh; `refresh`
 * asks the server and says whether the list changed. A failed ask keeps the
 * last list (or, never loaded, the fixed mission tools).
 */
export class McpToolCache {
  private list: readonly McpToolInfo[] | null = null;
  private loadedAt = 0;
  private key = "";

  constructor(
    private readonly fetch: () => Promise<IpcReply>,
    private readonly opts: { ttlMs?: number; now?: () => number } = {},
  ) {}

  get loaded() {
    return this.list !== null;
  }

  async get(): Promise<readonly McpToolInfo[]> {
    const now = (this.opts.now ?? Date.now)();
    if (this.list && now - this.loadedAt < (this.opts.ttlMs ?? TOOLS_CACHE_MS)) return this.list;
    await this.refresh();
    return this.list ?? MISSION_MCP_TOOLS;
  }

  /** Asks the server; true when the list differs from the one before (not on the first load). */
  async refresh(): Promise<boolean> {
    const reply = await this.fetch().catch(() => null);
    // A brain process between turns: the next turn is another run, so the list is asked again then.
    if (reply && !reply.ok && reply.idle) this.loadedAt = 0;
    if (!reply?.ok || !reply.tools) return false;
    const key = JSON.stringify(reply.tools);
    const changed = this.list !== null && key !== this.key;
    this.list = reply.tools;
    this.key = key;
    this.loadedAt = (this.opts.now ?? Date.now)();
    return changed;
  }
}

const rpcError = (id: JsonRpcId, code: number, message: string) => ({
  jsonrpc: "2.0" as const,
  id,
  error: { code, message },
});

/**
 * One JSON-RPC message from the executor; the response, or null for a
 * notification. Only what an MCP client needs from a tools-only server.
 */
export async function handleMcpMessage(
  message: unknown,
  call: ToolCaller,
  scope?: CommandScope,
  /** Protocol 8: the run's tools from the server (cached); without it, the fixed mission tools. */
  list?: ToolLister,
  /** The turn's permission profile (ADR 0053 §3): a `plan` turn's prompts are answered here, never asked. */
  profile: CommandProfile = "work",
): Promise<Record<string, unknown> | null> {
  if (typeof message !== "object" || message === null || Array.isArray(message)) {
    return rpcError(null, -32600, "Invalid request");
  }
  const m = message as { jsonrpc?: unknown; id?: unknown; method?: unknown; params?: unknown };
  const hasId = typeof m.id === "string" || typeof m.id === "number";
  const id: JsonRpcId = hasId ? (m.id as string | number) : null;
  if (m.jsonrpc !== "2.0" || typeof m.method !== "string")
    return hasId ? rpcError(id, -32600, "Invalid request") : null;
  // Notifications (`notifications/initialized`, `notifications/cancelled`…) need no answer.
  if (!hasId) return null;
  const params = (typeof m.params === "object" && m.params !== null ? m.params : {}) as Record<string, unknown>;
  switch (m.method) {
    case "initialize":
      return {
        jsonrpc: "2.0",
        id,
        result: {
          protocolVersion: typeof params.protocolVersion === "string" ? params.protocolVersion : MCP_PROTOCOL_VERSION,
          capabilities: { tools: { listChanged: Boolean(list) } },
          serverInfo: { name: "agentes", version: RUNNER_VERSION },
          instructions: list
            ? "Tools of agentes.chat for this agent: its connectors, context, Drive and, in a mission, the mission tools (keep the plan with update_plan, report milestones, ask decisions with ask_decision, ask approval before any merge, deploy or rollback). When a tool says to stop and wait, end your turn."
            : "Tools of agentes.chat for this mission: keep the plan with update_plan, report milestones, ask decisions with ask_decision, ask for a review when you have something to show, and ask approval before any merge, deploy or rollback.",
        },
      };
    case "ping":
      return { jsonrpc: "2.0", id, result: {} };
    case "tools/list":
      return {
        jsonrpc: "2.0",
        id,
        result: {
          // Read-only tools say so (Codex runs them without an approval even when told to ask).
          tools: (list ? await list() : MISSION_MCP_TOOLS).map((tool) =>
            READ_ONLY_TOOLS.has(tool.name) ? { ...tool, annotations: { readOnlyHint: true } } : tool,
          ),
        },
      };
    case "tools/call": {
      const name = typeof params.name === "string" ? params.name : "";
      const tools = list ? await list() : MISSION_MCP_TOOLS;
      if (!tools.some((t) => t.name === name)) return rpcError(id, -32602, `Unknown tool: ${name}`);
      const args =
        typeof params.arguments === "object" && params.arguments !== null && !Array.isArray(params.arguments)
          ? (params.arguments as Record<string, unknown>)
          : {};
      // Claude Code's permission prompt: always an answer it understands (allow or deny JSON), never an error.
      if (name === PERMISSION_TOOL) {
        const answer = await permissionPrompt(args, call, { ...(scope ? { scope } : {}), profile });
        return { jsonrpc: "2.0", id, result: { content: [{ type: "text", text: JSON.stringify(answer) }] } };
      }
      const reply = await call(name, args);
      return {
        jsonrpc: "2.0",
        id,
        result: {
          content: [{ type: "text", text: reply.ok ? reply.text : reply.error }],
          isError: !reply.ok,
        },
      };
    }
    default:
      return rpcError(id, -32601, `Method not found: ${m.method}`);
  }
}

/** What Claude Code's `--permission-prompt-tool` must answer. */
export type PermissionAnswer =
  | { behavior: "allow"; updatedInput: Record<string, unknown> }
  | { behavior: "deny"; message: string };

/**
 * Claude Code asks (`--permission-prompt-tool mcp__agentes__permission_prompt`)
 * when a command isn't on the task's allow list, and the runner asks the same
 * for each of Codex's command and file approvals (ADR 0053 §3): one decision
 * for both. First what the computer decides by itself (`localVerdict`):
 * deny-list commands and secrets are refused at once (never shown to anyone);
 * plain reads (`ls` of any folder, read-only git, a GET with curl in a work
 * turn) are allowed at once, with no card and nothing posted; in a `plan` turn
 * everything else is refused. The rest goes to the server, which allows it by
 * a mission rule or code's rules for a run, or posts the command card in the
 * thread. Then we ask the server every `pollMs` (short calls; no request stays
 * open) until someone answers or `waitMs` passes: then it is denied.
 */
export async function permissionPrompt(
  args: Record<string, unknown>,
  call: ToolCaller,
  opts: {
    waitMs?: number;
    pollMs?: number;
    sleep?: (ms: number) => Promise<void>;
    now?: () => number;
    /** Where the task runs: plain reads are allowed here without asking. */
    scope?: CommandScope;
    /** The turn's permission profile (default `work`). */
    profile?: CommandProfile;
  } = {},
): Promise<PermissionAnswer> {
  const toolName = typeof args.tool_name === "string" ? args.tool_name : "";
  const input =
    typeof args.input === "object" && args.input !== null && !Array.isArray(args.input)
      ? (args.input as Record<string, unknown>)
      : {};
  if (!toolName) return { behavior: "deny", message: "Unknown tool." };
  const verdict = localVerdict(toolName, input, opts.scope, opts.profile ?? "work");
  if (verdict?.behavior === "deny") return verdict;
  if (verdict?.behavior === "allow") return { behavior: "allow", updatedInput: input };
  const now = opts.now ?? Date.now;
  const sleep = opts.sleep ?? ((ms: number) => new Promise<void>((r) => setTimeout(r, ms)));
  const deadline = now() + (opts.waitMs ?? PERMISSION_WAIT_MS);
  const ask = async (a: Record<string, unknown>) => {
    let reply = await call(PERMISSION_TOOL, a);
    // The runner restarting or reconnecting: keep asking (within the wait), never a silent deny.
    while (!reply.ok && reply.transient && now() < deadline) {
      await sleep(opts.pollMs ?? PERMISSION_POLL_MS);
      reply = await call(PERMISSION_TOOL, a);
    }
    if (!reply.ok) return { error: reply.error };
    try {
      return JSON.parse(reply.text) as { behavior?: string; message?: string; status?: string; request_id?: string };
    } catch {
      return { error: "agentes.chat answered something unexpected." };
    }
  };
  let out = await ask({
    tool_name: toolName.slice(0, 64),
    input,
    ...(typeof args.tool_use_id === "string" ? { tool_use_id: args.tool_use_id.slice(0, 128) } : {}),
    ...(opts.scope ? { scope: opts.scope } : {}),
  });
  const requestId = "request_id" in out && typeof out.request_id === "string" ? out.request_id : "";
  for (;;) {
    if ("error" in out && out.error) return { behavior: "deny", message: `Not allowed: ${out.error}` };
    if ("behavior" in out && out.behavior === "allow") return { behavior: "allow", updatedInput: input };
    if ("behavior" in out && out.behavior === "deny") {
      return { behavior: "deny", message: String(out.message ?? "A person said no.").slice(0, 500) };
    }
    if (!requestId || now() >= deadline) return { behavior: "deny", message: PERMISSION_TIMEOUT_MESSAGE };
    await sleep(opts.pollMs ?? PERMISSION_POLL_MS);
    out = await ask({ request_id: requestId });
  }
}

/**
 * `agentes-runner mcp --task <id>`: serves MCP on stdin/stdout until stdin
 * closes. Nothing else may be written to stdout (it is the protocol).
 */
export async function runMcpServer(options: {
  taskId: string;
  socketPath: string;
  /** From the env the executor got; else the task folder's token file. */
  token: string | null;
  tokenFile?: string;
  input?: NodeJS.ReadableStream;
  output?: NodeJS.WritableStream;
  scope?: CommandScope;
  /** The turn's permission profile (default: `AGENTES_MCP_PROFILE`, else `work`). */
  profile?: CommandProfile;
  refreshMs?: number;
}): Promise<number> {
  const token =
    options.token ??
    (() => {
      try {
        return options.tokenFile ? readFileSync(options.tokenFile, "utf8").trim() : "";
      } catch {
        return "";
      }
    })();
  const out = options.output ?? process.stdout;
  const write = (msg: unknown) => out.write(`${JSON.stringify(msg)}\n`);
  const call: ToolCaller = (tool, args) => ipcCall(options.socketPath, { taskId: options.taskId, token, tool, args });
  // The run's tools, asked from the server through the daemon (cached here: one process per task or run).
  const cache = new McpToolCache(() =>
    ipcCall(options.socketPath, { taskId: options.taskId, token, tool: "", args: {}, kind: "list" }),
  );
  const list: ToolLister = () => cache.get();
  // A list that changed (a scope granted, a connector added, a mission thread): the executor re-reads it.
  const refresher = setInterval(() => {
    if (!cache.loaded) return;
    void cache.refresh().then((changed) => {
      if (changed) write({ jsonrpc: "2.0", method: "notifications/tools/list_changed" });
    });
  }, options.refreshMs ?? TOOLS_REFRESH_MS);
  refresher.unref?.();
  const scope = options.scope ?? mcpScopeFromEnv(process.env);
  const profile = options.profile ?? mcpProfileFromEnv(process.env);
  const rl = createInterface({ input: options.input ?? process.stdin, crlfDelay: Number.POSITIVE_INFINITY });
  const inflight = new Set<Promise<void>>();
  for await (const line of rl) {
    if (!line.trim()) continue;
    let message: unknown;
    try {
      message = JSON.parse(line);
    } catch {
      write(rpcError(null, -32700, "Parse error"));
      continue;
    }
    const p = handleMcpMessage(message, call, scope, list, profile)
      .then((res) => {
        if (res) write(res);
      })
      .catch(() => undefined)
      .finally(() => inflight.delete(p));
    inflight.add(p);
  }
  await Promise.all(inflight);
  clearInterval(refresher);
  return 0;
}

