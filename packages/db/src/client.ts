import { resolve } from "node:path";
import { sql } from "drizzle-orm";
import type { PgDatabase, PgQueryResultHKT } from "drizzle-orm/pg-core";
import { drizzle as drizzlePglite } from "drizzle-orm/pglite";
import { migrate as migratePglite } from "drizzle-orm/pglite/migrator";
import { drizzle } from "drizzle-orm/postgres-js";
import { migrate } from "drizzle-orm/postgres-js/migrator";
import postgres from "postgres";
import { assertMigrationsMatch } from "./migration-guard";
import { openPglite, pgliteFolder } from "./pglite";
import * as schema from "./schema";
import { tracingLogger } from "./trace";

/**
 * Driver-agnostic database handle. A Postgres server goes through postgres.js; native mode
 * (`pglite:///folder`) and the tests (`test/pglite.ts`) through PGlite. Code outside this package
 * should depend on this type, never on a specific driver.
 */
export type Database = PgDatabase<PgQueryResultHKT, typeof schema>;

/** A transaction handle, accepted wherever a `Database` is, for writes that must commit together. */
export type Transaction = Parameters<Parameters<Database["transaction"]>[0]>[0];
/** Either the database or an open transaction. */
export type Executor = Database | Transaction;

/**
 * SQL migrations generated by drizzle-kit (plus hand-written ones). Resolved
 * relative to this file so it works both from source and from a bundled build.
 */
export const migrationsFolder = resolve(import.meta.dir, "../migrations");

export interface DatabaseOptions {
  url: string;
  poolMax: number;
}

export interface DatabaseHandle {
  db: Database;
  /** The postgres.js client, for LISTEN/NOTIFY (see `@agenteschat/adapters`); null on PGlite (one process). */
  client: postgres.Sql | null;
  /**
   * Applies pending migrations, after checking that the applied ones are
   * exactly this build's (`assertMigrationsMatch`). Safe to run
   * concurrently on a server: drizzle takes an advisory lock.
   */
  migrate: () => Promise<void>;
  /** Cheap connectivity check for health endpoints. */
  ping: () => Promise<void>;
  close: () => Promise<void>;
}

/** A Postgres server for a `postgres://` URL, the built-in database for `pglite:///folder` (`pglite.ts`). */
export function createDatabase(options: DatabaseOptions): DatabaseHandle {
  const folder = pgliteFolder(options.url);
  if (folder) return createPgliteDatabase(folder);
  const client = postgres(options.url, {
    max: options.poolMax,
    // Silence "relation already exists, skipping" notices from migrations.
    onnotice: () => {},
  });
  const db = drizzle(client, { schema, casing: "snake_case", logger: tracingLogger });
  serializeDates(client);
  return {
    db: db as unknown as Database,
    client,
    migrate: async () => {
      await assertMigrationsMatch(db as unknown as Database, migrationsFolder);
      await migrate(db, { migrationsFolder });
    },
    ping: async () => {
      await client`select 1`;
    },
    close: () => client.end({ timeout: 5 }),
  };
}

/**
 * Drizzle leaves the date types to its columns' encoders, which give strings, and postgres.js then sends a value as it
 * is. A `Date` beside a raw `sql` expression has no encoder and would throw while binding; PGlite takes one, so only a
 * real server shows it. Runs after `drizzle()`, which sets these serializers.
 */
export function serializeDates(client: postgres.Sql) {
  const text = (value: unknown) => (value instanceof Date ? value.toISOString() : value);
  for (const type of ["1082", "1114", "1184"]) client.options.serializers[type as unknown as number] = text;
}

function createPgliteDatabase(folder: string): DatabaseHandle {
  const { pg, ready } = openPglite(folder);
  const db = drizzlePglite(pg, { schema, casing: "snake_case", logger: tracingLogger });
  return {
    db: db as unknown as Database,
    client: null,
    migrate: async () => {
      await ready;
      await assertMigrationsMatch(db as unknown as Database, migrationsFolder);
      await migratePglite(db, { migrationsFolder });
    },
    ping: async () => {
      await ready;
      await pg.query("select 1");
    },
    close: async () => {
      await ready.catch(() => {});
      await pg.close();
    },
  };
}

/**
 * Creates monthly `messages` partitions for the current month and the next
 * `monthsAhead` (docs/adr/0009). Called on boot and daily by the workers.
 * Returns how many partitions were created.
 */
export async function ensureMessagePartitions(db: Database, monthsAhead = 2): Promise<number> {
  const result = await db.execute<{ created: number }>(
    sql`select agenteschat_ensure_message_partitions(${monthsAhead}::int) as created`,
  );
  const rows = rowsOf<{ created: number }>(result);
  return Number(rows[0]?.created ?? 0);
}

/** Rows of a raw `db.execute` result, whatever the driver (postgres.js returns an array, PGlite `{ rows }`). */
export function rowsOf<T>(result: unknown): T[] {
  return (Array.isArray(result) ? result : (result as { rows: T[] }).rows) as T[];
}
